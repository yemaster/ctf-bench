#!/usr/bin/env python3
"""Build the Pwn challenge toy binary with an encoded flag."""
from __future__ import annotations

import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src" / "vuln.c"
HEADER = HERE / "src" / "secret.h"
PUBLIC = HERE.parent / "public"
BIN = PUBLIC / "pwnme"

FLAG = (HERE / "flag.txt").read_text(encoding="utf-8").strip().encode()


def c_array(data: bytes) -> str:
    return ", ".join(f"0x{b:02x}" for b in data)


def main() -> None:
    enc_flag = bytes(f ^ ((i * 13 + 0x37) & 0xFF) for i, f in enumerate(FLAG))
    header = f"""/* generated by build.py -- instructor only */
#ifndef SECRET_H
#define SECRET_H
#define FLAGLEN {len(FLAG)}
const unsigned char flag_enc[FLAGLEN] = {{{c_array(enc_flag)}}};
#endif
"""
    HEADER.write_text(header, encoding="utf-8")
    PUBLIC.mkdir(parents=True, exist_ok=True)
    cmd = [
        "gcc", "-O0", "-fno-pie", "-no-pie", "-fno-stack-protector",
        "-Wall", "-Wextra", "-Wno-stringop-overflow",
        "-I", str(HERE / "src"), "-o", str(BIN), str(SRC),
    ]
    subprocess.run(cmd, check=True)
    BIN.chmod(0o755)
    print("built", BIN)


if __name__ == "__main__":
    main()
