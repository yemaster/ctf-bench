#!/usr/bin/env python3
"""Build the stripped Reverse challenge with a two-layer license check."""
from __future__ import annotations

import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src" / "checker.c"
HEADER = HERE / "src" / "secret.h"
PUBLIC = HERE.parent / "public"
BIN = PUBLIC / "checker"

KEY = b"R3v_P3rm_Ch41n_2025!"
FLAG = (HERE / "flag.txt").read_text(encoding="utf-8").strip().encode()

# A fixed non-trivial permutation of 0..KEYLEN-1.  The checker applies
# p[i] = key[PERM[i]] before the chained XOR layer.
PERM = [11, 3, 18, 0, 15, 7, 1, 19, 9, 12, 4, 16, 6, 2, 14, 8, 17, 5, 13, 10]
MAGIC = 0x5256334C  # "L3VR" in little-endian bytes

assert len(KEY) == len(PERM) == len(set(PERM)) == 20, (len(KEY), len(PERM))


def c_array(data: bytes | list[int]) -> str:
    return ", ".join(f"0x{b:02x}" for b in data)


def main() -> None:
    # Layer 1: byte permutation.  Layer 2: chained XOR with the previous
    # permuted byte and a position constant.
    target = bytearray()
    prev = 0x5A
    for i, pos in enumerate(PERM):
        p = KEY[pos]
        target.append((p ^ prev ^ ((i * 0x1D + 0x33) & 0xFF)) & 0xFF)
        prev = p

    # The winning flag is encoded with a key-dependent stream.  The binary
    # decodes it only after both check layers pass.
    enc_flag = bytes(
        f ^ ((KEY[i % len(KEY)] * 7 + i * 13 + 0x5A
              + KEY[(i + 1) % len(KEY)]) & 0xFF)
        for i, f in enumerate(FLAG)
    )

    header = f"""/* generated by build.py -- instructor only */
#ifndef SECRET_H
#define SECRET_H
#define LICENSE_MAGIC 0x{MAGIC:08x}u
#define KEYLEN {len(KEY)}
#define FLAGLEN {len(FLAG)}
typedef struct {{
    unsigned int magic;
    unsigned int key_len;
    unsigned int flag_len;
    unsigned char perm[KEYLEN];
    unsigned char target[KEYLEN];
    unsigned char flag_enc[FLAGLEN];
}} license_blob_t;
static const license_blob_t license_blob = {{
    .magic = LICENSE_MAGIC,
    .key_len = KEYLEN,
    .flag_len = FLAGLEN,
    .perm = {{{c_array(PERM)}}},
    .target = {{{c_array(target)}}},
    .flag_enc = {{{c_array(enc_flag)}}},
}};
#endif
"""
    HEADER.write_text(header, encoding="utf-8")
    PUBLIC.mkdir(parents=True, exist_ok=True)
    cmd = [
        "gcc", "-O0", "-fno-pie", "-no-pie", "-fno-stack-protector",
        "-Wall", "-Wextra", "-I", str(HERE / "src"),
        "-o", str(BIN), str(SRC), "-s",
    ]
    subprocess.run(cmd, check=True)
    BIN.chmod(0o755)
    print("built", BIN)


if __name__ == "__main__":
    main()
